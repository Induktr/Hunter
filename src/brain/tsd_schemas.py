# ---------------------------------------------------------------------------
# PHASE 1: Деконструкция (Вопросы "ЧТО?") - Полная матрица из 19 пунктов
# ---------------------------------------------------------------------------
class Phase1Deconstruction(BaseModel):
    q1_three_words: List[str] = Field(
        description="[ ] 1. 'Три Ключевых Слова': Если бы мне нужно было описать эту концепцию всего тремя словами, какие бы я выбрал? Паттерн Ответа: [Слово 1], [Слово 2], [Слово 3]."
    )
    q2_point_of_view: str = Field(
        description="[ ] 2. Определить 'Точку Зрения' (Контекст): С какой точки зрения эта концепция определяется и анализируется? (С точки зрения Бизнеса / Инженера / Пользователя / Системы)."
    )
    q3_golden_sentence: str = Field(
        description="[ ] 3. 'Золотое Предложение': Теперь, используя эти три слова, сформулировать одно, главное предложение, которое передает 80% смысла. Паттерн Ответа: По своей сути, [Концепция] — это [что-то], что [делает что-то] для [достижения чего-то]."
    )
    q4_technical_definition: str = Field(
        description="[ ] 4. Что это такое? (Определение): Дать короткое, технически точное определение в одном предложении. Что это — функция, объект, паттерн, API? Паттерн Ответа: '[Концепция] — это [тип], который [что делает]...'."
    )
    q5_signal_and_intent: str = Field(
        description="[ ] 5. О чем это 'говорит'? (Сигнал/Смысл): Какой 'сигнал' или 'сообщение' несет эта концепция, когда я вижу ее в коде? О чем она мне 'говорит'? Паттерн Ответа: 'Когда я вижу [Концепция], это говорит мне о том, что [смысл/намерение]...'."
    )
    q6_pragmatic_goal: str = Field(
        description="[ ] 6. В чем Цель? (Прагматика): Какую конкретную, измеримую, тактическую цель преследовали создатели? Что должно стать быстрее, проще, надежнее? Паттерн Ответа: 'Практическая цель — [ускорить/упростить/защитить] [конкретный процесс]...'."
    )
    q7_philosophical_mission: str = Field(
        description="[ ] 7. В чем Миссия? (Философия): В чем философская идея или стратегическое видение, которое лежит в основе этой концепции? Какое 'будущее' она пытается построить? Паттерн Ответа: 'Миссия этой технологии — [описание идеологии]...'."
    )
    q8_one_main_problem: str = Field(
        description="[ ] 8. Какую ОДНУ, главную проблему решает эта концепция? (Зачем ее вообще придумали?)."
    )
    q9_key_components: List[str] = Field(
        description="[ ] 9. Из каких КЛЮЧЕВЫХ 'частей' / 'терминов' она состоит? (Например, Event Loop состоит из Call Stack, Web APIs, Callback Queue)."
    )
    q10_interaction_flow: str = Field(
        description="[ ] 10. Как эти 'части' взаимодействуют друг с другом? (Какова их последовательность, кто кем управляет?)."
    )
    q11_action_synthesis: str = Field(
        description="[ ] 11. [Синтез действий]: Что делает эта концепция? 1. Выбери 1-3 ключевых слова. 2. Дай краткое объяснение каждому слову. 3. Объедини их в финальную формулу смысла (Пример React: Синхронизация. Состояние -> UI. Объединение: Синхронизация визуального отображения с текущим состоянием данных)."
    )
    q12_intentional_vs_accidental: str = Field(
        description="[ ] 12. 'Intentional vs. Accidental': А що робить ця концепція спеціально, а що — випадково? (Проаналізувати спеціальні наміри та випадкові побічні ефекти)."
    )
    q13_lifecycle_root: str = Field(
        description="[ ] 13. 'Lifecycle Root': З чого починається старт цієї концепції, і чим вона завершується? (Старт — це завжди 'Тертя', а кінець — це 'Тверда Система/SOP')."
    )
    q14_external_vs_internal: str = Field(
        description="[ ] 14. Какая внешняя сторона в [Концепция], а какая внутренняя? (Пример: Внешняя — UI/Интерфейс; Внутренняя — Логика распределения, память, потоки, битовая структура, DPC Latency, Hoisting, Heap/Stack)."
    )
    q15_dependencies: List[str] = Field(
        description="[ ] 15. Какие зависимости есть в [Концепция]? (Факторы зависимости, например метод replace() зависит от Regex и String)."
    )
    q16_visual_audit: str = Field(
        description="[ ] 16. [Visual Audit]: Отрисовать концепцию на Whiteboard (Схема: Данные -> Память -> Связи, указатели Stack -> Heap)."
    )
    q17_problem_origin: str = Field(
        description="[ ] 17. С чего началась проблема над данной концепцией? (Первопричина возникновения трения)."
    )
    q18_concept_triad: str = Field(
        description="[ ] 18. [Concept Triad] (Тройная философская трактовка): Раскрыть концепцию в трех разных вариациях (1. Прагматика, 2. Физика/Система, 3. Био-система/Психология)."
    )
    q19_foundational_substrate: str = Field(
        description="[ ] 19. На чём основана данная концепция? (Философия): Какая база лежит над этой концепцией, которая делает её такой? Паттерн Ответа: '[Концепция] основана на — [База/Субстрат], неужели это имело бы смысл без этого, основание всегда идёт от [База]'."
    )


